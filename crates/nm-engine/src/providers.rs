    #[test]
    fn a_local_file_is_checked() {
        let ok = "name = \"X\"\ndomains = [\"x.example\"]\n[imap]\nhost = \"imap.x.example\"\nport = 993\nsecurity = \"tls\"\n";
        let p = parse_local("x", ok).unwrap();
        assert_eq!((p.imap[0].username.as_str(), p.smtp.len()), ("%EMAILADDRESS%", 0));
        for (bad, why) in [
            (ok.replace("name = \"X\"\n", ""), "name"),
            (ok.replace("[\"x.example\"]", "[]"), "domains"),
            (ok.replace("\"tls\"", "\"none\""), "security"),
            (ok.replace("993", "0"), "port"),
            (ok.replace("imap.x.example", "imap x"), "invalid host"),
            (format!("{ok}colour = 1\n"), "unknown key"),
            (ok.replace("port = 993", "prot = 993"), "unknown key"),
        ] {
            let e = parse_local("x", &bad).unwrap_err();
            assert!(e.contains(why) && e.contains("x.toml"), "{why}: {e}");
        }
        let two = "name = \"Y\"\ndomains = [\"y.example\"]\n[[imap]]\nhost = \"a.y.example\"\nport = 993\nsecurity = \"tls\"\n[[imap]]\nhost = \"b.y.example\"\nport = 143\nsecurity = \"starttls\"\n";
        assert_eq!(parse_local("y", two).unwrap().imap.len(), 2);
    }

