/// `thunderbird.json`, as `scripts/update-autoconfig.py` writes it.
#[derive(Deserialize)]
struct TbFile {
    providers: Vec<TbProvider>,
}

#[derive(Deserialize)]
struct TbProvider {
    id: String,
    name: String,
    domains: Vec<String>,
    imap: Vec<TbServer>,
    #[serde(default)]
    smtp: Vec<TbServer>,
}

#[derive(Deserialize)]
struct TbServer {
    host: String,
    port: u16,
    security: String,
    username: String,
    #[serde(default)]
    auth: Vec<String>,
}

impl TbServer {
    fn server(self) -> Result<Server, String> {
        check_host(&self.host)?;
        Ok(Server {
            host: self.host,
            port: self.port,
            security: parse_security(&self.security)?,
            username: self.username,
            auth: self.auth,
        })
    }
}

pub fn parse_thunderbird(text: &str) -> Result<Vec<Provider>, String> {
    let file: TbFile = serde_json::from_str(text).map_err(|e| format!("thunderbird.json: {e}"))?;
    file.providers
        .into_iter()
        .map(|p| {
            let id = p.id.clone();
            let servers = |v: Vec<TbServer>| v.into_iter().map(TbServer::server).collect::<Result<Vec<_>, _>>();
            Ok(Provider {
                id: p.id,
                name: p.name,
                origin: Origin::Thunderbird,
                domains: p.domains,
                mx: Vec::new(),
                imap: servers(p.imap).map_err(|e| format!("thunderbird.json, {id}: {e}"))?,
                smtp: servers(p.smtp).map_err(|e| format!("thunderbird.json, {id}: {e}"))?,
            })
        })
        .collect()
}

/// One of our files (`data/providers/local/<id>.toml`): `name`, `domains`,
/// `mx` (optional), `[imap]` (or `[[imap]]` for several), `[smtp]`
/// (optional, same).
pub fn parse_local(id: &str, text: &str) -> Result<Provider, String> {
    let at = |e: String| format!("data/providers/local/{id}.toml: {e}");
    let doc: DocumentMut = text.parse().map_err(|e| at(format!("{e}")))?;
    for (k, _) in doc.iter() {
        if !["name", "domains", "mx", "imap", "smtp"].contains(&k) {
            return Err(at(format!("unknown key {k:?}")));
        }
    }
    let name = doc.get("name").and_then(Item::as_str).ok_or_else(|| at("name (text) is missing".into()))?.to_string();
    let domains = domain_list(&doc, "domains").map_err(at)?;
    if domains.is_empty() {
        return Err(at("domains is missing or empty".into()));
    }
    let mx = domain_list(&doc, "mx").map_err(at)?;
    let imap = local_servers(&doc, "imap").map_err(at)?;
    if imap.is_empty() {
        return Err(at("[imap] is missing".into()));
    }
    let smtp = local_servers(&doc, "smtp").map_err(at)?;
    Ok(Provider { id: id.into(), name, origin: Origin::Local, domains, mx, imap, smtp })
}

fn domain_list(doc: &DocumentMut, key: &str) -> Result<Vec<String>, String> {
    let Some(item) = doc.get(key) else { return Ok(Vec::new()) };
    let array = item.as_array().ok_or_else(|| format!("{key} must be a list of domains"))?;
    array
        .iter()
        .map(|v| {
            let d = v.as_str().ok_or_else(|| format!("{key} must be a list of domains"))?.to_ascii_lowercase();
            check_host(&d).map_err(|_| format!("{key}: invalid domain {d:?}"))?;
            Ok(d)
        })
        .collect()
}

fn local_servers(doc: &DocumentMut, key: &str) -> Result<Vec<Server>, String> {
    let tables: Vec<&toml_edit::Table> = match doc.get(key) {
        None => return Ok(Vec::new()),
        Some(Item::Table(t)) => vec![t],
        Some(Item::ArrayOfTables(a)) => a.iter().collect(),
        Some(_) => return Err(format!("{key} must be a table [{key}] or [[{key}]]")),
    };
    tables
        .into_iter()
        .map(|t| {
            for (k, _) in t.iter() {
                if !["host", "port", "security", "username"].contains(&k) {
                    return Err(format!("[{key}]: unknown key {k:?}"));
                }
            }
            let text = |k: &str| t.get(k).and_then(Item::as_str).ok_or_else(|| format!("[{key}]: {k} (text) is missing"));
            let host = text("host")?.to_ascii_lowercase().replace("%emaildomain%", "%EMAILDOMAIN%");
            check_host(&host).map_err(|e| format!("[{key}]: {e}"))?;
            let port = t
                .get("port")
                .and_then(Item::as_integer)
                .and_then(|p| u16::try_from(p).ok().filter(|p| *p > 0))
                .ok_or_else(|| format!("[{key}]: port (1 to 65535) is missing"))?;
            let security = parse_security(text("security")?).map_err(|e| format!("[{key}]: {e}"))?;
            let username = t.get("username").and_then(Item::as_str).unwrap_or("%EMAILADDRESS%").to_string();
            Ok(Server { host, port, security, username, auth: Vec::new() })
        })
        .collect()
}

