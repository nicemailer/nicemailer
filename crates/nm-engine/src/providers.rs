use std::sync::OnceLock;

use nm_api::{DiscoveryReport, ImapParams, ProviderMatch, ServerCandidate};
use serde::Deserialize;
use toml_edit::{DocumentMut, Item};

use crate::config::Security;

// `LOCAL_PROVIDERS`, generated by `build.rs`.
include!(concat!(env!("OUT_DIR"), "/local_providers.rs"));

const THUNDERBIRD: &str = include_str!("../../../data/providers/thunderbird.json");

/// The only login NiceMailer knows: a password (`LOGIN` / `PLAIN`, over
/// TLS). Thunderbird's name for it.
const PASSWORD: &str = "password-cleartext";

/// Where a provider comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Origin {
    Local,
    Thunderbird,
}

impl Origin {
    pub fn as_str(self) -> &'static str {
        match self {
            Origin::Local => "local",
            Origin::Thunderbird => "thunderbird",
        }
    }
}

/// A server of a provider, as its file says it: `host` and `username` may
/// hold placeholders (`%EMAILDOMAIN%`, `%EMAILADDRESS%`,
/// `%EMAILLOCALPART%`), replaced by the parts of the address.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Server {
    pub host: String,
    pub port: u16,
    pub security: Security,
    pub username: String,
    /// Login methods, in Thunderbird's words; empty: not said (our files),
    /// taken as a password.
    pub auth: Vec<String>,
}

impl Server {
    /// Whether NiceMailer can log in: with a password. A server that only
    /// takes OAuth2 (Outlook.com) cannot be used yet.
    pub fn usable(&self) -> bool {
        self.auth.is_empty() || self.auth.iter().any(|a| a == PASSWORD)
    }

    /// The server for `email`: placeholders replaced, the user name left
    /// out when it is the address (the default of `accounts.toml`).
    pub fn params(&self, email: &str) -> ImapParams {
        let username = fill(&self.username, email);
        ImapParams {
            host: fill(&self.host, email).to_ascii_lowercase(),
            port: self.port,
            security: security_name(self.security).into(),
            username: (username != email).then_some(username),
            ca_file: None,
        }
    }
}

/// A provider: the domains it hosts, and its servers.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Provider {
    /// The file name (`infomaniak`) or Thunderbird's id (`googlemail.com`).
    pub id: String,
    pub name: String,
    pub origin: Origin,
    /// Domains of the addresses it hosts.
    pub domains: Vec<String>,
    /// Domains of its MX servers (our files only): a domain of any name
    /// whose MX is under one of them is hosted there.
    pub mx: Vec<String>,
    pub imap: Vec<Server>,
    pub smtp: Vec<Server>,
}

impl Provider {
    /// Its first IMAP server NiceMailer can log in to.
    pub fn imap(&self) -> Option<&Server> {
        self.imap.iter().find(|s| s.usable())
    }
}

/// Every provider, and an index from a domain (of addresses or of MX
/// servers) to the provider listing it.
#[derive(Debug)]
pub struct Providers {
    list: Vec<Provider>,
    index: HashMap<String, usize>,
}

impl Providers {
    /// The database built into the core, read once. Its files are checked
    /// by the unit tests, so an error here means a broken build.
    pub fn get() -> Result<&'static Providers, String> {
        // Rust note: `OnceLock` runs the closure the first time only, even
        // when several threads ask at once; later calls get the same value.
        static ONCE: OnceLock<Result<Providers, String>> = OnceLock::new();
        ONCE.get_or_init(|| {
            let mut local = Vec::new();
            for (id, text) in LOCAL_PROVIDERS {
                local.push(parse_local(id, text)?);
            }
            Ok(Providers::new(local, parse_thunderbird(THUNDERBIRD)?))
        })
        .as_ref()
        .map_err(Clone::clone)
    }

    /// The index: our providers first, so that a domain both sources name
    /// is ours; within a source, the first provider naming a domain keeps it.
    pub fn new(local: Vec<Provider>, thunderbird: Vec<Provider>) -> Providers {
        let list: Vec<Provider> = local.into_iter().chain(thunderbird).collect();
        let mut index = HashMap::new();
        for (i, p) in list.iter().enumerate() {
            for d in p.domains.iter().chain(&p.mx) {
                index.entry(d.clone()).or_insert(i);
            }
        }
        Providers { list, index }
    }

    pub fn len(&self) -> usize {
        self.list.len()
    }

    pub fn is_empty(&self) -> bool {
        self.list.is_empty()
    }

    /// The provider of an address's domain: the domain itself must be
    /// listed (`gmail.com`), not one of its parents.
    pub fn by_domain(&self, domain: &str) -> Option<&Provider> {
        self.index.get(domain).map(|&i| &self.list[i])
    }

    /// The provider of the first MX server (by preference) that one lists:
    /// the server's name, then each parent down to its organizational
    /// domain (`aspmx.l.google.com`, `l.google.com`, `google.com`). Never
    /// above it: `com` names no provider, but `co.uk` must not be tried
    /// either. Gives the provider, the domain found, and the MX server.
    pub fn by_mx<'a>(&self, mx_hosts: &'a [String]) -> Option<(&Provider, String, &'a str)> {
        for host in mx_hosts {
            let org = nm_store::auth::organizational_domain(host);
            let mut name = host.as_str();
            loop {
                if let Some(p) = self.by_domain(name) {
                    return Some((p, name.to_string(), host.as_str()));
                }
                if name == org {
                    break;
                }
                match name.split_once('.') {
                    Some((_, parent)) if parent.len() >= org.len() => name = parent,
                    _ => break,
                }
            }
        }
        None
    }
}

/// The local part and the domain (lower case) of an address, or why it is
/// not one.
pub fn split_address(email: &str) -> Result<(&str, String), String> {
    let email = email.trim();
    let (local, domain) = email.rsplit_once('@').ok_or_else(|| format!("{email:?} is not an email address: no @"))?;
    let domain = domain.trim_end_matches('.').to_ascii_lowercase();
    if local.is_empty() || domain.is_empty() || !domain.contains('.') || domain.contains(char::is_whitespace) {
        return Err(format!("{email:?} is not an email address"));
    }
    Ok((local, domain))
}

/// An account the core has already: its key, and its address when known
/// (a disabled account may have none).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Existing {
    pub key: String,
    pub email: Option<String>,
}

/// The account key proposed for `email` (`docs/accounts.md`, "The key"),
/// and why:
///
/// - the first account of a domain is named after the domain:
///   `pierre.dupont@toto-mail.com` gives `toto-mail` ([`domain_key`]);
/// - when an account of the same domain exists (`jean@toto-mail.com`
///   added before), or when another account has that name already (one of
///   `toto-mail.fr`), the whole address: `pierre_dupont_toto_mail_com`
///   ([`key_from_email`]).
///
/// "The same domain" is the address's domain itself, case aside:
/// `toto-mail.com` and `mail.toto-mail.com` are two domains (their keys,
/// both `toto-mail`, are then told apart by the second rule).
pub struct KeyChoice {
    pub key: String,
    /// `domain` or `address`.
    pub source: &'static str,
    pub domain_key: String,
    /// The key of an account of the same domain, if any.
    pub domain_account: Option<String>,
}

pub fn choose_key(email: &str, existing: &[Existing]) -> Result<KeyChoice, String> {
    let (_, domain) = split_address(email)?;
    let domain_key = domain_key(&domain);
    let domain_account = existing
        .iter()
        .find(|a| a.email.as_deref().and_then(|e| split_address(e).ok()).is_some_and(|(_, d)| d == domain))
        .map(|a| a.key.clone());
    let taken = existing.iter().any(|a| a.key.eq_ignore_ascii_case(&domain_key));
    Ok(if domain_account.is_none() && !taken {
        KeyChoice { key: domain_key.clone(), source: "domain", domain_key, domain_account }
    } else {
        KeyChoice { key: key_from_email(email), source: "address", domain_key, domain_account }
    })
}

/// The name of a domain, without its public suffix nor its subdomains:
/// the label before the suffix (`toto-mail.com`: `toto-mail`;
/// `mail.example.co.uk`: `example`), as the organizational domain gives it
/// (`nm_store::auth`). Characters a key cannot hold become `_` (a domain
/// holds none but in its IDN form, which is ASCII).
pub fn domain_key(domain: &str) -> String {
    let org = nm_store::auth::organizational_domain(domain);
    let name = org.split('.').next().unwrap_or(&org);
    let key: String = name.chars().map(|c| if c.is_ascii_alphanumeric() || c == '-' { c.to_ascii_lowercase() } else { '_' }).collect();
    if key.is_empty() { "account".into() } else { key }
}

/// The account key made from the whole address: lower case, every character
/// that is not an ASCII letter or digit becomes `_`, several in a row one
/// only, none at the ends. `pierre.dupont@toto-mail.com` gives
/// `pierre_dupont_toto_mail_com`. Cut to 64 characters, the most a key may
/// have (`config_write::check_key`).
pub fn key_from_email(email: &str) -> String {
    let mut key = String::new();
    for c in email.trim().chars().flat_map(char::to_lowercase) {
        if c.is_ascii_alphanumeric() {
            key.push(c);
        } else if !key.is_empty() && !key.ends_with('_') {
            key.push('_');
        }
    }
    key.truncate(64);
    let key = key.trim_end_matches('_').to_string();
    if key.is_empty() { "account".into() } else { key }
}

/// Whether two hosts belong to one organization: the same host, or the
/// same organizational domain (`imap.gmail.com`, `smtp.gmail.com`). The
/// rule by which the sender may use the IMAP password for SMTP
/// (`secrets.rs`, `docs/sending.md`): the IMAP password is only ever tried
/// where it would be used.
pub fn same_organization(a: &str, b: &str) -> bool {
    let (a, b) = (a.to_ascii_lowercase(), b.to_ascii_lowercase());
    a == b || nm_store::auth::organizational_domain(&a) == nm_store::auth::organizational_domain(&b)
}

/// The SMTP servers to try for an IMAP host the user gave
/// (`docs/accounts.md`): the host with `imap` replaced by `smtp` in its
/// first label holding it (`imap.example.fr`: `smtp.example.fr`), then the
/// host itself; each on the two submission ports, 465 (TLS from the first
/// byte, preferred by RFC 8314) then 587 (STARTTLS). Port 25 is left out:
/// it is for servers relaying between them, and providers block it.
pub fn smtp_guesses(imap: &ImapParams) -> Vec<ServerCandidate> {
    let host = imap.host.to_ascii_lowercase();
    let mut hosts = Vec::new();
    let labels: Vec<&str> = host.split('.').collect();
    if let Some(i) = labels.iter().position(|l| l.contains("imap")) {
        let mut renamed = labels.clone();
        let label = labels[i].replacen("imap", "smtp", 1);
        renamed[i] = &label;
        hosts.push((renamed.join("."), "smtp_name"));
    }
    hosts.push((host.clone(), "same_host"));
    let mut out = Vec::new();
    for (h, origin) in hosts {
        for (port, security) in [(465, "tls"), (587, "starttls")] {
            out.push(ServerCandidate {
                server: ImapParams {
                    host: h.clone(),
                    port,
                    security: security.into(),
                    username: imap.username.clone(),
                    ca_file: imap.ca_file.clone(),
                },
                origin: origin.into(),
            });
        }
    }
    out
}

/// Whether the MX of the domain are needed: only when the domain itself
/// is not listed.
pub fn needs_mx(providers: &Providers, email: &str) -> bool {
    split_address(email).is_ok_and(|(_, d)| providers.by_domain(&d).is_none())
}

/// What the database says of `email`, given the IMAP server the user gave
/// (if any) and the MX lookup (`None`: not made; `Err`: failed).
///
/// - IMAP: the server given, else the provider's (by domain, else by MX).
/// - SMTP: the provider's servers, when its IMAP server is the one used
///   (else they may be another provider's); then, for a server the user
///   gave, the guesses of [`smtp_guesses`]; for a provider listing no SMTP
///   server, the same guesses from its IMAP server. Each once.
pub fn plan(
    providers: &Providers,
    email: &str,
    existing: &[Existing],
    given: Option<&ImapParams>,
    mx: Option<Result<Vec<String>, String>>,
) -> Result<DiscoveryReport, String> {
    let (_, domain) = split_address(email)?;
    let key = choose_key(email, existing)?;
    let by_domain = providers.by_domain(&domain).map(|p| matched(p, &domain, None));
    let (mx_hosts, mx_error, mx_looked_up) = match mx {
        Some(Ok(v)) => (v, None, true),
        Some(Err(e)) => (Vec::new(), Some(e), true),
        None => (Vec::new(), None, false),
    };
    let by_mx = if by_domain.is_some() {
        None
    } else {
        providers.by_mx(&mx_hosts).map(|(p, found, host)| matched(p, &found, Some(host)))
    };
    let provider = by_domain.as_ref().or(by_mx.as_ref()).and_then(|m| providers.list.iter().find(|p| p.id == m.id));

    let provider_imap = provider.and_then(Provider::imap).map(|s| s.params(email));
    let imap = match (given, &provider_imap) {
        (Some(g), _) => Some(ServerCandidate { server: g.clone(), origin: "given".into() }),
        (None, Some(p)) => Some(ServerCandidate { server: p.clone(), origin: "provider".into() }),
        (None, None) => None,
    };

    let mut smtp: Vec<ServerCandidate> = Vec::new();
    if let (Some(p), Some(used)) = (provider, &imap) {
        // The provider's SMTP servers belong with its IMAP server: tried
        // only when that one is used.
        if provider_imap.as_ref().is_some_and(|pi| pi.host.eq_ignore_ascii_case(&used.server.host)) {
            for s in p.smtp.iter().filter(|s| s.usable()) {
                smtp.push(ServerCandidate { server: s.params(email), origin: "provider".into() });
            }
        }
    }
    if let Some(used) = &imap
        && (used.origin == "given" || smtp.is_empty())
    {
        smtp.extend(smtp_guesses(&used.server));
    }
    let mut seen = Vec::new();
    smtp.retain(|c| {
        let k = (c.server.host.clone(), c.server.port);
        let new = !seen.contains(&k);
        seen.push(k);
        new
    });

    Ok(DiscoveryReport {
        key: key.key,
        key_source: key.source.into(),
        domain_key: key.domain_key,
        domain_account: key.domain_account,
        domain,
        by_domain,
        mx: mx_hosts,
        mx_looked_up,
        mx_error,
        by_mx,
        imap,
        smtp,
    })
}

fn matched(p: &Provider, found: &str, mx_host: Option<&str>) -> ProviderMatch {
    ProviderMatch {
        id: p.id.clone(),
        name: p.name.clone(),
        source: p.origin.as_str().into(),
        matched: found.into(),
        mx_host: mx_host.map(Into::into),
        imap_unsupported: p.imap().is_none(),
    }
}

/// `template` with the parts of `email` in place of the placeholders.
fn fill(template: &str, email: &str) -> String {
    let (local, domain) = split_address(email).unwrap_or((email, String::new()));
    template.replace("%EMAILADDRESS%", email.trim()).replace("%EMAILLOCALPART%", local).replace("%EMAILDOMAIN%", &domain)
}

fn security_name(s: Security) -> &'static str {
    match s {
        Security::Tls => "tls",
        Security::Starttls => "starttls",
        Security::None => "none",
    }
}

fn parse_security(s: &str) -> Result<Security, String> {
    match s {
        "tls" => Ok(Security::Tls),
        "starttls" => Ok(Security::Starttls),
        // A provider's server is never on this Mac: clear text is refused.
        other => Err(format!("security must be tls or starttls, not {other:?}")),
    }
}

/// A host name, placeholders allowed, or why not.
fn check_host(host: &str) -> Result<(), String> {
    let sample = host.replace("%EMAILDOMAIN%", "example.com");
    let ok = sample.split('.').count() >= 2
        && sample.split('.').all(|l| {
            !l.is_empty() && l.len() <= 63 && l.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') && !l.starts_with('-')
        });
    if ok { Ok(()) } else { Err(format!("invalid host {host:?}")) }
}

