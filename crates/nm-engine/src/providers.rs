//! The database of mail providers, and what it says of an address
//! (`docs/accounts.md`, "Finding the servers"; the files are described in
//! `data/providers/README.md`).
//!
//! Two sources, built into the core when it is compiled:
//! - `data/providers/thunderbird.json`: Thunderbird's ISP database,
//!   converted by `make autoconfig` (`scripts/update-autoconfig.py`);
//! - `data/providers/local/*.toml`: our own providers, by hand. They win
//!   over Thunderbird's for the domains they name.
//!
//! Everything here is pure: the DNS lookup and the SMTP attempts are in
//! `discover.rs`, which hands their results to [`plan`]. The report says
//! what was found and how, step by step: `nicemailer account add` prints
//! it, so that nothing is chosen without the user seeing why.

